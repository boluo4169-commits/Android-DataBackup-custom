HERE = os.path.dirname(os.path.abspath(__file__))
COMPANION_DIR = os.path.dirname(HERE)
SRC_DIR = os.path.join(COMPANION_DIR, "src")
BAT_PATH = os.path.join(COMPANION_DIR, "DataBackupFTPServer.bat")

# (src 下的文件名, 提取到 %TEMP% 后的文件名)；ftp_server.py 必须最后（bat 切到文件末尾）
EMBED_FILES = (
    ("ftp_core.py", "ftp_core.py"),
    ("DataBackupFTPServer.py", "ftp_server.py"),
)
MARKER_HEAD = "###FILE:%s###"


