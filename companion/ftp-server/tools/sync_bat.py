def build_bat() -> str:
    """生成完整 bat 文本：启动器 + 内嵌源码块"""
    parts = [LAUNCHER.rstrip("\n"), "", "###PYCODE###"]
    for src_name, embed_name in EMBED_FILES:
        path = os.path.join(SRC_DIR, src_name)
        with open(path, "r", encoding="utf-8") as f:
            content = f.read().replace("\r\n", "\n").rstrip("\n")
        parts.append(MARKER_HEAD % embed_name)
        parts.append(content)
    return "\n".join(parts) + "\n"


def extract(bat_text: str) -> dict:
    """按 bat 的提取规则（PowerShell 行号切片）还原内嵌源码。键为嵌入名。"""
    embed_names = [name for _, name in EMBED_FILES]
    lines = bat_text.replace("\r\n", "\n").split("\n")
    idx = {}
    for i, line in enumerate(lines):
        for name in embed_names:
            if line.strip() == MARKER_HEAD % name:
                idx[name] = i
    if len(idx) != len(embed_names):
        raise RuntimeError("marker 缺失: %s" % (set(embed_names) - set(idx)))
    out = {}
    for pos, name in enumerate(embed_names):
        start = idx[name] + 1
        if pos + 1 < len(embed_names):
            end = idx[embed_names[pos + 1]]  # 到下一个 marker（不含）
        else:
            end = len(lines)  # 最后一个：到文件末尾
        out[name] = "\n".join(lines[start:end]).rstrip("\n")
    return out


def verify(bat_text: str) -> bool:
    """内嵌副本与 src/ 源码逐字节比对"""
    ok = True
    embedded = extract(bat_text)
    for src_name, embed_name in EMBED_FILES:
        with open(os.path.join(SRC_DIR, src_name), "r", encoding="utf-8") as f:
            src = f.read().replace("\r\n", "\n").rstrip("\n")
        if embedded[embed_name] != src:
            ok = False
            print("[不一致] src/%s → 内嵌 %s：两份内容不同" % (src_name, embed_name))
        else:
            print("[一致] src/%s → 内嵌 %s（%d 行）" % (src_name, embed_name, src.count("\n") + 1))
    return ok


def main():
    parser = argparse.ArgumentParser(description="同步 src/*.py 到 DataBackupFTPServer.bat")
    parser.add_argument("--check", action="store_true", help="只检查是否已同步，不写文件")
    args = parser.parse_args()

    if args.check:
        if not os.path.exists(BAT_PATH):
            print("[错误] 找不到 %s" % BAT_PATH)
            return 1
        with open(BAT_PATH, "r", encoding="utf-8") as f:
            bat_text = f.read()
        return 0 if verify(bat_text) else 1

    bat_text = build_bat()
    if not verify(bat_text):
        print("[错误] 生成结果自检未通过，未写入")
        return 1
    # newline="\r\n" 保证 bat 为 CRLF；encoding 不带 BOM（cmd 解析更稳）
    with open(BAT_PATH, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(bat_text)
    size = os.path.getsize(BAT_PATH)
    total = bat_text.count("\n") + 1
    print("[完成] 已写入 %s（%d 行 / %d 字节，无 BOM + CRLF）" % (BAT_PATH, total, size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
